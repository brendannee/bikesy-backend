#!/usr/bin/env node
// Generate bench/areas/<region>-wilderness.geojson from a region's routing extract:
// designated wilderness (boundary=protected_area areas titled "Wilderness Area" or tagged
// protected_area=wilderness_preserve), where bicycles are prohibited by law. Areas only
// partly inside the extract (incomplete multipolygons) are skipped by osmium.
// Requires osmium-tool, like scripts/prepare-osm.py.
//   node bench/build-areas.mjs --region tahoe --pbf path/to/region.osm.pbf
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { BENCH_DIR } from './lib/catalog.mjs';
import { OSM_ATTRIBUTION } from './lib/open-data.mjs';

const { values } = parseArgs({ options: { region: { type: 'string' }, pbf: { type: 'string' }, out: { type: 'string' } } });
if (!values.region || !values.pbf) {
  console.error('Usage: node bench/build-areas.mjs --region REGION --pbf REGION.osm.pbf [--out FILE]');
  process.exit(2);
}
export const isWilderness = tags => tags.boundary === 'protected_area' &&
  (tags.protection_title === 'Wilderness Area' || tags.protected_area === 'wilderness_preserve');

const work = mkdtempSync(resolve(tmpdir(), 'bench-areas-'));
try {
  const filtered = resolve(work, 'areas.osm.pbf'), exported = resolve(work, 'areas.geojsonseq');
  execFileSync('osmium', ['tags-filter', '--overwrite', resolve(values.pbf), 'wr/boundary=protected_area', '-o', filtered], { stdio: 'inherit' });
  execFileSync('osmium', ['export', '--overwrite', filtered, '-f', 'geojsonseq', '--geometry-types=polygon', '-o', exported], { stdio: 'inherit' });
  const round = c => typeof c[0] === 'number' ? [Number(c[0].toFixed(5)), Number(c[1].toFixed(5))] : c.map(round);
  const features = readFileSync(exported, 'utf8').split('\n').filter(Boolean)
    .map(line => JSON.parse(line.replace(/^\x1e/, '')))
    .filter(f => isWilderness(f.properties))
    .map(f => ({ type: 'Feature', properties: { name: f.properties.name, protection_title: f.properties.protection_title, operator: f.properties.operator },
      geometry: { type: f.geometry.type, coordinates: round(f.geometry.coordinates) } }))
    .sort((a, b) => a.properties.name.localeCompare(b.properties.name));
  const out = resolve(values.out ?? resolve(BENCH_DIR, 'areas', `${values.region}-wilderness.geojson`));
  writeFileSync(out, JSON.stringify({ type: 'FeatureCollection',
    source: `OSM boundary=protected_area wilderness from ${values.pbf.replace(/^.*\//, '')}, generated by bench/build-areas.mjs (ODbL)`,
    attribution: OSM_ATTRIBUTION, features }) + '\n');
  console.log(`Wrote ${features.length} areas to ${out}: ${features.map(f => f.properties.name).join(', ')}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
